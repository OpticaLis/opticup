  //   const HEADER = `\n  DECLARE\n    v_jwt_role text := ...\n  BEGIN\n    IF v_jwt_role ...\n`;
  //   return currentDef.replace(/AS \$function\$\s*(DECLARE|BEGIN)/, `AS \$function\$${HEADER}$1`);
  // Example for "flip security_invoker=on on view":
