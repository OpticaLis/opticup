// JWT validation header to N RPCs, flip security_invoker=on on N views) to
// many DB objects, hand-rolling a migration generator each time is wasteful
// (~10 minutes per SPEC) and error-prone. This skeleton:
//   1. Connects via DATABASE_URL_READONLY from $HOME/.optic-up/credentials.env
//      (Iron Rule 23 — no secrets in the repo).
//   2. Fetches `pg_get_functiondef` / `pg_get_viewdef` for each named object.
//   3. Applies a per-object `transform(name, currentDef)` callback.
//   4. Writes the resulting migration .sql file under `migrations/`.
//   5. Self-deletes after use (Iron Rule 31 compliance).
//
// USAGE — copy this file, fill in the marked TODOs, run via `node`,
// then delete the copy before commit. The script never goes into git.
